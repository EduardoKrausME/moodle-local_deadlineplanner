namespace local_deadlineplanner\local;

final class provider_registry {
    public static function get(string $modname): ?deadline_provider_interface {
        switch ($modname) {
            case 'assign':
                return new assign_deadline_provider();
            case 'quiz':
                return new quiz_deadline_provider();
            default:
                return null;
        }
    }
}
